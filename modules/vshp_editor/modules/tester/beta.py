"""Бета-движок заливки вопросов — собран поверх release.

Что осталось от release (главное — стабильность):
  * те же тайминги config.Timing (пауза 1-2 с после создания поля и варианта);
  * та же полная проверка страницы после каждого добавленного варианта;
  * те же повторы и починка расхождений (verify / _repair);
  * то же сохранение и возврат к списку вопросов.

Что ускорено:
  * переходы по ссылкам — page.goto(wait_until="commit"): мимо Turbolinks,
    без ожидания скриптов страницы (переопределён только goto_link,
    поэтому open_create_form / пагинация ускоряются автоматически);
  * запись текста не ждёт инициализации CKEditor — SET_FIELD_JS кладёт значение
    в textarea напрямую, а если редактор уже есть, работает через него;
  * сохранение кликает и сразу ждёт список вопросов, не дожидаясь навигации.
"""

from __future__ import annotations

from .release import Actions


class BetaActions(Actions):
    """Ускоренный вариант: та же логика проверок, быстрее навигация."""

    wait_ckeditor = False

    # ---------------------------------------------------------------- навигация
    def goto_link(self, locator, wait_until: str = "commit"):
        """Переход по ссылке без ожидания полной загрузки страницы."""
        return super().goto_link(locator, wait_until=wait_until)

    # ------------------------------------------------------------ сохранение
    def save_question(self):
        """Клик и ожидание списка — без ожидания навигации (быстрее, чем в release)."""
        button = self._save_button_ready()
        button.click(no_wait_after=True)
        return self._after_save()
